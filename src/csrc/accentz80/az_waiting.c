/* az_waiting.c -- measures where the Accent SA's firmware waits, and writes az_waiting.inc from it: the table
 * az_board.c counts the firmware's own work against (az_board_take_work), which is how a voice tells a text that has
 * ended from one whose next clause is still being read (../accentpc/as_voice.c, issue #8).  A tool, run by hand when
 * a firmware is added:
 *
 *   az_waiting <U4 file> <U5 file> [<U5 file> ...]  >  az_waiting.inc
 *
 * For each U5 (a firmware version; the table is keyed by its FNV-1a, so the board knows which it holds) the unit is
 * run on the real host and every instruction's address is taken (az_board_take_pcs) in the states in which the
 * firmware has, for certain, nothing to read or say:
 *   idle       3 s after power-up, the greeting flushed (ash_boot)
 *   commands   1 s after each settings command the voices send (rate, pitch, voice, intonation, the index marks'
 *              two), from 0.3 s after the unit stopped being busy with it
 *   cancel     2 s after a Ctrl-X into a long text, from 0.3 s after it
 *   speech     each of the short texts below, at three rates: the 30 ms block at whose end the unit is no longer
 *              busy -- the block a voice asks about first, with the last pauses going to the chip and the
 *              utterance closing in it -- and the 2 s after it.  Each text is ONE clause: with nothing after it
 *              there is no next clause to read.  (Between two clauses the unit is not busy either, and runs its
 *              rules: that is the work the table must NOT hold, and why longer texts are not measured.)  A little
 *              idle time before each text, 0 to 25 ms, moves the blocks against the speech.
 * Addresses up to 4 bytes apart (a Z80 instruction's length) are joined into one range.  The summary goes to stderr.
 * MIT.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "az_host.h"
#include "az_board.h"

static unsigned char seen[0x10000];
static uint16_t pcs[0x10000];

static void take(az_board *b, int keep)
{
    int i, n = az_board_take_pcs(b, pcs, 0x10000);
    if (keep)
        for (i = 0; i < n; i++)
            seen[pcs[i]] = 1;
}

static void say(as_host *h, const char *s, int speech)
{
    ash_say(h, (const unsigned char *)s, (int)strlen(s), speech);
}

/* until the unit is no longer busy (at most `limit`), in 30 ms blocks as a voice renders; the watch then holds the
   last block's addresses only */
static void until_idle(as_host *h, az_board *b, double limit)
{
    const double *y;
    double t = 0.0;
    do {
        take(b, 0);
        ash_run(h, 0.03, 0.0005, &y);
        t += 0.03;
    } while (ash_busy(h, 0.03, 1.5) && t < limit);
}

static void blocks(as_host *h, double seconds)
{
    const double *y;
    double t;
    for (t = 0.0; t < seconds; t += 0.03)
        ash_run(h, 0.03, 0.0005, &y);
}

static unsigned long fnv(const unsigned char *p, size_t n)
{
    unsigned long hsh = 2166136261UL;
    size_t i;
    for (i = 0; i < n; i++)
        hsh = ((hsh ^ p[i]) * 16777619UL) & 0xFFFFFFFFUL;
    return hsh;
}

static unsigned char *slurp(const char *path, size_t *n)
{
    FILE *f = fopen(path, "rb");
    unsigned char *d;
    long len;
    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    len = ftell(f);
    fseek(f, 0, SEEK_SET);
    d = (unsigned char *)malloc((size_t)len + 1);
    if (d && fread(d, 1, (size_t)len, f) != (size_t)len) {
        free(d);
        d = NULL;
    }
    fclose(f);
    *n = (size_t)len;
    return d;
}

static const char *base(const char *path)           /* the file's name without its folders */
{
    const char *p = path, *q;
    for (q = path; *q; q++)
        if (*q == '/' || *q == '\\')
            p = q + 1;
    return p;
}

static const char *const COMMANDS[] = {"\x1bR0", "\x1bR9", "\x1bR5", "\x1bP0", "\x1bP9", "\x1bP5", "\x1bV0", "\x1bV9",
                                       "\x1bV5", "\x1bM1", "\x1bM0", "\x1bYX\x1b=Y"};
static const char *const TEXTS[] = {
    "hello\r", "Hello.\r", "yes?\r", "stop!\r", "a\r", "Z\r", "42\r", "1996\r", "testing one two three\r", "OK\r",
    "the quick brown fox\r", "Accent\r", "file edit view\r", "x y z\r", "100 percent\r", "good morning\r",
    "\x06" "marked \x06" "words\r", "desktop list\r", "e mail\r", "3.14\r"};

int main(int argc, char **argv)
{
    unsigned char *u4;
    size_t n4 = 0;
    int k;
    if (argc < 3) {
        fprintf(stderr, "usage: az_waiting <U4> <U5> [<U5> ...] > az_waiting.inc\n");
        return 2;
    }
    u4 = slurp(argv[1], &n4);
    if (!u4) {
        fprintf(stderr, "az_waiting: cannot read %s\n", argv[1]);
        return 1;
    }
    printf("/* az_waiting.inc -- where the Accent SA's firmware waits, by firmware: GENERATED by az_waiting.c (how it is\n"
           "   measured is said there); do not edit.  Each range is first and last instruction address, inclusive. */\n");
    for (k = 2; k < argc; k++) {
        char err[256];
        unsigned char *u5;
        size_t n5 = 0, i;
        as_host *h;
        az_board *b;
        int rate, a, ranges = 0, addrs = 0, col = 0;
        u5 = slurp(argv[k], &n5);
        if (!u5) {
            fprintf(stderr, "az_waiting: cannot read %s\n", argv[k]);
            return 1;
        }
        memset(seen, 0, sizeof seen);
        h = azh_create(u5, n5, u4, n4, NULL, 22050.0, err, (int)sizeof err);
        if (!h) {
            fprintf(stderr, "az_waiting: %s\n", err);
            return 1;
        }
        b = (az_board *)ash_board_of(h);
        ash_boot(h, 4.0);
        blocks(h, 0.5);
        take(b, 0);                        /* the watch starts here */
        blocks(h, 3.0);
        take(b, 1);                        /* idle */
        for (i = 0; i < sizeof COMMANDS / sizeof COMMANDS[0]; i++) {
            say(h, COMMANDS[i], 0);
            until_idle(h, b, 2.0);
            blocks(h, 0.3);
            take(b, 0);
            blocks(h, 1.0);
            take(b, 1);                    /* after a command */
        }
        say(h, "This is a long text that will be cut short by a control X, well before it has all been said.\r", 1);
        blocks(h, 0.6);
        ash_cancel(h, 0.6);
        blocks(h, 0.3);
        take(b, 0);
        blocks(h, 2.0);
        take(b, 1);                        /* after a cancel */
        for (rate = 0; rate < 3; rate++) {
            say(h, rate == 0 ? "\x1bR5" : rate == 1 ? "\x1bR9" : "\x1bR0", 0);
            until_idle(h, b, 2.0);
            for (i = 0; i < sizeof TEXTS / sizeof TEXTS[0]; i++) {
                const double *y;
                if (i % 6)
                    ash_run(h, 0.005 * (double)(i % 6), 0.0005, &y);
                say(h, TEXTS[i], 1);
                until_idle(h, b, 20.0);
                blocks(h, 2.0);
                take(b, 1);                /* the block the utterance closed in, then waiting */
            }
        }
        ash_destroy(h);
        printf("/* %s */\n#define AZ_WAITING_%d_U5 0x%08lXUL\nstatic const uint16_t AZ_WAITING_%d[][2] = {\n   ",
               base(argv[k]), k - 2, fnv(u5, n5), k - 2);
        for (a = 0; a < 0x10000; a++) {
            int first, last;
            if (!seen[a])
                continue;
            first = last = a;
            addrs++;
            while (1) {
                int j, next = -1;
                for (j = last + 1; j <= last + 4 && j < 0x10000; j++)
                    if (seen[j]) {
                        next = j;
                        break;
                    }
                if (next < 0)
                    break;
                last = next;
                addrs++;
            }
            if (col == 6) {
                printf("\n   ");
                col = 0;
            }
            printf(" {0x%04X, 0x%04X},", first, last);
            col++;
            ranges++;
            a = last;
        }
        printf("\n};\n");
        fprintf(stderr, "%s: FNV-1a %08lX, %d instruction addresses in %d ranges\n", argv[k], fnv(u5, n5), addrs, ranges);
        free(u5);
    }
    printf("#define AZ_WAITING_FIRMWARES %d\n", argc - 2);
    free(u4);
    return 0;
}
